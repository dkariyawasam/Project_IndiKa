const struct TrainerMonItemCustomMoves *GetIndigoGymLeaderParty(u16 trainerId)
{
    if (!IsIndigoLeagueTrainerBattle())
        return NULL;
    switch (trainerId)
    {
    case TRAINER_LEADER_BROCK_7: return sParty_IndigoBROCK_7;
    case TRAINER_LEADER_MISTY_7: return sParty_IndigoMISTY_7;
    case TRAINER_LEADER_LT_SURGE_7: return sParty_IndigoLT_SURGE_7;
    case TRAINER_LEADER_ERIKA_7: return sParty_IndigoERIKA_7;
    case TRAINER_LEADER_KOGA_7: return sParty_IndigoKOGA_7;
    case TRAINER_LEADER_BLAINE_7: return sParty_IndigoBLAINE_7;
    case TRAINER_LEADER_SABRINA_7: return sParty_IndigoSABRINA_7;
    case TRAINER_LEADER_GIOVANNI: return sParty_IndigoGIOVANNI;
    default: return NULL;
    }
}
